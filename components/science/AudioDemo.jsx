'use client';
import { useEffect, useRef, useState } from 'react';
import { Play, Square, Volume2, VolumeX } from 'lucide-react';
import { playAnimalSound, stopAnimalSound, setMasterVolume, getAudioAnalyser } from '../../lib/soundSynth';

/**
 * Synthesized demonstration tone. NOT a recording of the animal, and labelled as such.
 * The visualizer only runs while a tone is playing, and shows a static state under reduced motion.
 */
export default function AudioDemo({ species }) {
  const { audio } = species;
  const canvas = useRef(null);
  const [playing, setPlaying] = useState(false);
  const [volume, setVolume] = useState(0.8);
  const [muted, setMuted] = useState(false);
  const [unsupported, setUnsupported] = useState(false);

  useEffect(() => { setUnsupported(!(window.AudioContext || window.webkitAudioContext)); }, []);
  useEffect(() => () => stopAnimalSound(), []);
  useEffect(() => { stopAnimalSound(); }, [species.slug]);

  useEffect(() => {
    const cv = canvas.current;
    if (!cv) return undefined;
    const ctx = cv.getContext('2d');
    const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    let raf = 0;

    const paintIdle = () => {
      ctx.clearRect(0, 0, cv.width, cv.height);
      ctx.strokeStyle = '#1B3025';
      ctx.lineWidth = 2;
      ctx.beginPath(); ctx.moveTo(0, cv.height / 2); ctx.lineTo(cv.width, cv.height / 2); ctx.stroke();
    };
    const paintBars = (data) => {
      ctx.clearRect(0, 0, cv.width, cv.height);
      const bw = cv.width / data.length;
      ctx.fillStyle = '#D4FF72';
      data.forEach((v, i) => {
        const h = Math.max(2, (v / 255) * cv.height);
        ctx.fillRect(i * bw + 1, cv.height - h, bw - 2, h);
      });
    };

    if (!playing) { paintIdle(); return undefined; }
    if (reduce) { paintBars(new Uint8Array(48).map((_, i) => 40 + (i < 12 ? 150 - i * 8 : 30))); return undefined; }

    const loop = () => {
      const an = getAudioAnalyser();
      if (an) {
        const data = new Uint8Array(an.frequencyBinCount);
        an.getByteFrequencyData(data);
        paintBars(data);
      }
      raf = requestAnimationFrame(loop);
    };
    loop();
    return () => cancelAnimationFrame(raf);
  }, [playing]);

  const toggle = () => {
    if (playing) { stopAnimalSound(); return; }
    playAnimalSound(audio.params, setPlaying);
  };
  const changeVolume = (v) => { setVolume(v); setMuted(v === 0); setMasterVolume(v); };
  const toggleMute = () => {
    const next = !muted;
    setMuted(next);
    setMasterVolume(next ? 0 : volume || 0.8);
  };

  return (
    <div className="rounded-2xl border border-white/10 p-5">
      <span className="unverified-pill" style={{ borderColor: 'rgba(212,255,114,.5)', color: '#D4FF72' }}>Synthesized demonstration</span>
      <p className="mt-3 text-[.9rem] text-muted">
        This is a simple tone generated by your browser to suggest the character of the call ({audio.description.toLowerCase()}). It is <strong className="font-medium text-ivory">not a recording</strong> of a real {species.name}. Authentic recordings will be added only where provenance and usage rights are confirmed.
      </p>

      <canvas ref={canvas} width={480} height={56} className="mt-4 h-14 w-full rounded-xl bg-forest-2" aria-hidden="true" />

      <div className="mt-4 flex flex-wrap items-center gap-4">
        <button type="button" onClick={toggle} disabled={unsupported} className="btn" aria-pressed={playing}>
          {playing ? <Square className="h-4 w-4" aria-hidden="true" /> : <Play className="h-4 w-4" aria-hidden="true" />}
          {playing ? 'Stop' : 'Play demonstration'}
        </button>
        <div className="flex items-center gap-2">
          <button type="button" onClick={toggleMute} aria-label={muted ? 'Unmute' : 'Mute'} className="rounded-full p-2 text-muted hover:text-lime">
            {muted ? <VolumeX className="h-4 w-4" /> : <Volume2 className="h-4 w-4" />}
          </button>
          <label className="sr-only" htmlFor={`vol-${species.slug}`}>Volume</label>
          <input id={`vol-${species.slug}`} type="range" min="0" max="1" step="0.05" value={muted ? 0 : volume} onChange={(e) => changeVolume(parseFloat(e.target.value))} className="w-28 accent-[#D4FF72]" />
        </div>
        <span className="text-[.75rem] text-botanical" role="status">{playing ? 'Playing' : unsupported ? 'Audio is not supported in this browser' : 'Stopped'}</span>
      </div>
      <p className="mt-4 text-[.82rem] text-botanical">{audio.hint}</p>
    </div>
  );
}
